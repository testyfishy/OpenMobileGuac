/** The shape every session table has (same keys, functions with the same parameters). */
export type SessionStrings = typeof sessionStringsEn;

/** The active session table. Live binding: read it at call time. */
export let sessionStrings: SessionStrings = sessionStringsEn;

/** Install the table for the active language (the app shell calls this). */
export function setSessionStrings(table: SessionStrings): void {
  sessionStrings = table;
}
